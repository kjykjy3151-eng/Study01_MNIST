/** 3x3 무패딩 합성곱에 ReLU 를 이어서 계산합니다.
 *
 * 두 합성곱층 모두 뒤에 ReLU 가 붙으므로 한 번에 처리합니다.
 */
function 합성곱_렐루(입력, 입력_채널, 입력_크기, 가중치, 편향, 출력_채널) {
    const 출력_크기 = 입력_크기 - 2;
    const 출력 = new Float32Array(출력_채널 * 출력_크기 * 출력_크기);
    const 입력_면 = 입력_크기 * 입력_크기;
    const 출력_면 = 출력_크기 * 출력_크기;

    for (let 출력_c = 0; 출력_c < 출력_채널; 출력_c++) {
        for (let y = 0; y < 출력_크기; y++) {
            for (let x = 0; x < 출력_크기; x++) {
                let 합 = 편향[출력_c];
                for (let 입력_c = 0; 입력_c < 입력_채널; 입력_c++) {
                    const 입력_기준 = 입력_c * 입력_면;
                    const 가중치_기준 = (출력_c * 입력_채널 + 입력_c) * 9;
                    for (let ky = 0; ky < 3; ky++) {
                        const 행_기준 = 입력_기준 + (y + ky) * 입력_크기 + x;
                        const 커널_기준 = 가중치_기준 + ky * 3;
                        합 += 입력[행_기준] * 가중치[커널_기준]
                            + 입력[행_기준 + 1] * 가중치[커널_기준 + 1]
                            + 입력[행_기준 + 2] * 가중치[커널_기준 + 2];
                    }
                }
                출력[출력_c * 출력_면 + y * 출력_크기 + x] = 합 > 0 ? 합 : 0;
            }
        }
    }
    return 출력;
}

/** 2x2 최대풀링. 해상도를 절반으로 줄입니다. */
function 최대풀링(입력, 채널, 입력_크기) {
    const 출력_크기 = 입력_크기 >> 1;
    const 출력 = new Float32Array(채널 * 출력_크기 * 출력_크기);
    const 입력_면 = 입력_크기 * 입력_크기;
    const 출력_면 = 출력_크기 * 출력_크기;

    for (let c = 0; c < 채널; c++) {
        for (let y = 0; y < 출력_크기; y++) {
            for (let x = 0; x < 출력_크기; x++) {
                const 기준 = c * 입력_면 + y * 2 * 입력_크기 + x * 2;
                let 최대 = 입력[기준];
                if (입력[기준 + 1] > 최대) 최대 = 입력[기준 + 1];
                if (입력[기준 + 입력_크기] > 최대) 최대 = 입력[기준 + 입력_크기];
                if (입력[기준 + 입력_크기 + 1] > 최대) 최대 = 입력[기준 + 입력_크기 + 1];
                출력[c * 출력_면 + y * 출력_크기 + x] = 최대;
            }
        }
    }
    return 출력;
}

/** 완전연결층. 가중치는 (출력수, 입력수) 순서로 저장되어 있습니다. */
function 완전연결(입력, 가중치, 편향, 출력_수, 렐루_적용) {
    const 입력_수 = 입력.length;
    const 출력 = new Float32Array(출력_수);
    for (let o = 0; o < 출력_수; o++) {
        let 합 = 편향[o];
        const 기준 = o * 입력_수;
        for (let i = 0; i < 입력_수; i++) 합 += 입력[i] * 가중치[기준 + i];
        출력[o] = 렐루_적용 && 합 < 0 ? 0 : 합;
    }
    return 출력;
}

/** 소프트맥스. 최댓값을 빼서 지수 계산의 넘침을 막습니다.
 *
 * 파이썬 쪽은 로그 소프트맥스 뒤에 지수를 취하는데, 결과는 이것과 같습니다.
 */
function 소프트맥스(점수들) {
    let 최대 = 점수들[0];
    for (let i = 1; i < 점수들.length; i++) if (점수들[i] > 최대) 최대 = 점수들[i];
    const 출력 = new Float32Array(점수들.length);
    let 합 = 0;
    for (let i = 0; i < 점수들.length; i++) {
        const 값 = Math.exp(점수들[i] - 최대);
        출력[i] = 값;
        합 += 값;
    }
    for (let i = 0; i < 출력.length; i++) 출력[i] /= 합;
    return 출력;
}

/** 구조 정보와 가중치 버퍼로 추론 가능한 모델을 만듭니다.
 *
 * 인자:
 *     구조: 가중치/구조.json 을 파싱한 객체
 *     배열버퍼: 가중치/mnist_cnn.bin 의 ArrayBuffer
 * 반환:
 *     예측(), 평균, 표준편차 를 가진 객체
 */
export function 모델_만들기(구조, 배열버퍼) {
    if (배열버퍼.byteLength !== 구조.전체_바이트) {
        throw new Error(
            `가중치 파일 크기가 ${배열버퍼.byteLength} 바이트입니다. `
            + `${구조.전체_바이트} 바이트여야 합니다.`
        );
    }

    const 전체 = new Float32Array(배열버퍼);
    const 텐서 = {};
    for (const 정보 of 구조.텐서들) {
        텐서[정보.이름] = 전체.subarray(정보.시작, 정보.시작 + 정보.개수);
    }

    function 예측(정규화된_입력) {
        if (정규화된_입력.length !== 784) {
            throw new Error(`입력 길이가 ${정규화된_입력.length} 입니다. 784 여야 합니다.`);
        }
        let 값 = 합성곱_렐루(정규화된_입력, 1, 28, 텐서["합성곱1.weight"], 텐서["합성곱1.bias"], 32);
        값 = 합성곱_렐루(값, 32, 26, 텐서["합성곱2.weight"], 텐서["합성곱2.bias"], 64);
        값 = 최대풀링(값, 64, 24);
        // 최대풀링 결과가 이미 (채널, 행, 열) 순서라 평탄화가 따로 필요 없습니다.
        값 = 완전연결(값, 텐서["완전연결1.weight"], 텐서["완전연결1.bias"], 128, true);
        값 = 완전연결(값, 텐서["완전연결2.weight"], 텐서["완전연결2.bias"], 10, false);
        return 소프트맥스(값);
    }

    return { 예측, 평균: 구조.평균, 표준편차: 구조.표준편차 };
}

/** 브라우저에서 가중치를 내려받아 모델을 만듭니다.
 *
 * 인자:
 *     기준경로: 가중치 폴더의 상대 경로. 끝에 슬래시를 붙입니다.
 */
export async function 모델_불러오기(기준경로 = "가중치/") {
    const 구조_응답 = await fetch(기준경로 + "구조.json");
    if (!구조_응답.ok) throw new Error(`구조.json 을 불러오지 못했습니다 (${구조_응답.status})`);
    const 구조 = await 구조_응답.json();

    const 가중치_응답 = await fetch(기준경로 + 구조.가중치_파일);
    if (!가중치_응답.ok) {
        throw new Error(`${구조.가중치_파일} 을 불러오지 못했습니다 (${가중치_응답.status})`);
    }
    return 모델_만들기(구조, await 가중치_응답.arrayBuffer());
}

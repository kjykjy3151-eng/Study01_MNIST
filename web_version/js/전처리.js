// 그림판에 그린 그림을 MNIST 와 같은 형식의 28x28 로 다듬습니다.
// desktop_version/app.py 의 전처리() 와 같은 결과를 내야 합니다.
//
// 이 파일은 DOM 에 의존하지 않습니다. 캔버스에서 꺼낸 회색조 배열만 받습니다.

const 최종_크기 = 28;
const 목표_긴변 = 20;   // MNIST 는 숫자를 20x20 안에 맞춰 넣은 데이터입니다.

/** 파이썬 round() 와 같은 반올림.
 *
 * 파이썬은 0.5 를 짝수 쪽으로 보냅니다(round(2.5) == 2). 자바스크립트
 * Math.round 는 위로 올리므로(2.5 -> 3) 그대로 쓰면 크기와 이동량이
 * 파이썬과 갈릴 수 있습니다.
 */
function 짝수_반올림(값) {
    const 내림 = Math.floor(값);
    const 나머지 = 값 - 내림;
    if (나머지 > 0.5) return 내림 + 1;
    if (나머지 < 0.5) return 내림;
    return 내림 % 2 === 0 ? 내림 : 내림 + 1;
}

/** Lanczos3 필터. */
function 란초스(t) {
    if (t < 0) t = -t;
    if (t === 0) return 1;
    if (t >= 3) return 0;
    const 파이t = Math.PI * t;
    return (Math.sin(파이t) / 파이t) * (Math.sin(파이t / 3) / (파이t / 3));
}

/** 한 축의 리샘플링 계수를 PIL 과 같은 규칙으로 계산합니다.
 *
 * 축소할 때는 필터 폭을 배율만큼 넓혀(안티에일리어싱) 여러 입력 픽셀을
 * 함께 섞습니다. 이 처리가 없으면 계단 현상이 남습니다.
 */
function 계수_만들기(입력_크기, 출력_크기) {
    const 배율 = 입력_크기 / 출력_크기;
    const 필터_배율 = Math.max(1, 배율);
    const 지지폭 = 3 * 필터_배율;
    const 계수들 = [];

    for (let 출력 = 0; 출력 < 출력_크기; 출력++) {
        const 중심 = (출력 + 0.5) * 배율;
        const 시작 = Math.max(Math.floor(중심 - 지지폭 + 0.5), 0);
        const 끝 = Math.min(Math.floor(중심 + 지지폭 + 0.5), 입력_크기);
        const 개수 = 끝 - 시작;
        const 가중치 = new Float64Array(Math.max(개수, 1));

        let 합 = 0;
        for (let i = 0; i < 개수; i++) {
            const w = 란초스((i + 시작 - 중심 + 0.5) / 필터_배율);
            가중치[i] = w;
            합 += w;
        }
        if (합 !== 0) for (let i = 0; i < 가중치.length; i++) 가중치[i] /= 합;
        계수들.push({ 시작, 가중치, 개수 });
    }
    return 계수들;
}

/** 0~255 범위로 반올림해 자릅니다. PIL 의 8비트 저장과 맞춥니다. */
function 여덟비트로(값) {
    const 정수 = Math.round(값);
    if (정수 < 0) return 0;
    if (정수 > 255) return 255;
    return 정수;
}

/** PIL 과 같은 순서로 가로를 먼저, 세로를 나중에 줄입니다. */
function 축소하기(입력, 너비, 높이, 새_너비, 새_높이) {
    const 가로_계수 = 계수_만들기(너비, 새_너비);
    const 중간 = new Uint8Array(새_너비 * 높이);
    for (let y = 0; y < 높이; y++) {
        for (let x = 0; x < 새_너비; x++) {
            const { 시작, 가중치, 개수 } = 가로_계수[x];
            let 합 = 0;
            for (let i = 0; i < 개수; i++) 합 += 입력[y * 너비 + 시작 + i] * 가중치[i];
            중간[y * 새_너비 + x] = 여덟비트로(합);
        }
    }

    const 세로_계수 = 계수_만들기(높이, 새_높이);
    const 출력 = new Uint8Array(새_너비 * 새_높이);
    for (let y = 0; y < 새_높이; y++) {
        const { 시작, 가중치, 개수 } = 세로_계수[y];
        for (let x = 0; x < 새_너비; x++) {
            let 합 = 0;
            for (let i = 0; i < 개수; i++) 합 += 중간[(시작 + i) * 새_너비 + x] * 가중치[i];
            출력[y * 새_너비 + x] = 여덟비트로(합);
        }
    }
    return 출력;
}

/** 손으로 그린 그림을 MNIST 와 같은 형식의 28x28 로 다듬습니다.
 *
 * 인자:
 *     회색조: 0~255 Uint8Array. 검은 배경에 흰 글씨
 *     너비, 높이: 회색조 배열의 크기
 * 반환:
 *     길이 784 의 Float32Array(0.0~1.0). 그린 것이 없으면 null
 */
export function 전처리(회색조, 너비, 높이) {
    // 1) 글씨가 있는 영역의 경계 상자를 찾습니다.
    let 위 = -1, 아래 = -1, 왼쪽 = 너비, 오른쪽 = -1;
    for (let y = 0; y < 높이; y++) {
        for (let x = 0; x < 너비; x++) {
            if (회색조[y * 너비 + x] !== 0) {
                if (위 < 0) 위 = y;
                아래 = y;
                if (x < 왼쪽) 왼쪽 = x;
                if (x > 오른쪽) 오른쪽 = x;
            }
        }
    }
    if (위 < 0) return null;   // 아무것도 그리지 않은 빈 캔버스

    const 상자_너비 = 오른쪽 - 왼쪽 + 1;
    const 상자_높이 = 아래 - 위 + 1;
    const 잘라낸 = new Uint8Array(상자_너비 * 상자_높이);
    for (let y = 0; y < 상자_높이; y++) {
        for (let x = 0; x < 상자_너비; x++) {
            잘라낸[y * 상자_너비 + x] = 회색조[(위 + y) * 너비 + 왼쪽 + x];
        }
    }

    // 2) 비율을 유지한 채 긴 변이 20픽셀이 되도록 줄입니다.
    const 비율 = 목표_긴변 / Math.max(상자_너비, 상자_높이);
    const 새_너비 = Math.max(1, 짝수_반올림(상자_너비 * 비율));
    const 새_높이 = Math.max(1, 짝수_반올림(상자_높이 * 비율));
    const 축소 = 축소하기(잘라낸, 상자_너비, 상자_높이, 새_너비, 새_높이);

    // 3) 28x28 검은 도화지 한가운데에 붙입니다.
    const 도화지 = new Uint8Array(최종_크기 * 최종_크기);
    const 시작_x = (최종_크기 - 새_너비) >> 1;
    const 시작_y = (최종_크기 - 새_높이) >> 1;
    for (let y = 0; y < 새_높이; y++) {
        for (let x = 0; x < 새_너비; x++) {
            도화지[(시작_y + y) * 최종_크기 + 시작_x + x] = 축소[y * 새_너비 + x];
        }
    }

    // 4) 무게중심을 (13.5, 13.5) 로 옮깁니다. MNIST 가 그렇게 만들어진 데이터입니다.
    let 전체_밝기 = 0, 가중_y = 0, 가중_x = 0;
    for (let y = 0; y < 최종_크기; y++) {
        for (let x = 0; x < 최종_크기; x++) {
            const 값 = 도화지[y * 최종_크기 + x];
            전체_밝기 += 값;
            가중_y += y * 값;
            가중_x += x * 값;
        }
    }

    let 결과_배열 = 도화지;
    if (전체_밝기 > 0) {
        const 이동_x = 짝수_반올림(13.5 - 가중_x / 전체_밝기);
        const 이동_y = 짝수_반올림(13.5 - 가중_y / 전체_밝기);
        if (이동_x !== 0 || 이동_y !== 0) {
            결과_배열 = new Uint8Array(최종_크기 * 최종_크기);
            for (let y = 0; y < 최종_크기; y++) {
                const 원_y = y - 이동_y;
                if (원_y < 0 || 원_y >= 최종_크기) continue;
                for (let x = 0; x < 최종_크기; x++) {
                    const 원_x = x - 이동_x;
                    if (원_x < 0 || 원_x >= 최종_크기) continue;
                    결과_배열[y * 최종_크기 + x] = 도화지[원_y * 최종_크기 + 원_x];
                }
            }
        }
    }

    // 5) 0~255 를 0.0~1.0 으로 바꿉니다. 정규화는 부르는 쪽에서 합니다.
    const 결과 = new Float32Array(최종_크기 * 최종_크기);
    for (let i = 0; i < 결과.length; i++) 결과[i] = 결과_배열[i] / 255;
    return 결과;
}
